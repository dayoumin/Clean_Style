import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const sharp = createRequire(require.resolve('next/package.json'))('sharp');
const directory = path.join(root, 'public/images/adult-integrity/question-ocean');
const originals = JSON.parse(await readFile(path.join(directory, 'index.json'), 'utf8'));
const manifest = [];
let originalBytes = 0;
let webpBytes = 0;

for (const original of originals) {
  const input = await readFile(path.join(directory, original.file));
  const output = await sharp(input).webp({ quality: 85, effort: 5 }).toBuffer();
  const metadata = await sharp(output).metadata();
  if (metadata.width !== 435 || metadata.height !== 214) throw new Error('Unexpected scene dimensions');
  const sha256 = createHash('sha256').update(output).digest('hex');
  const file = `${original.file.replace(/\.png$/, '')}-${sha256.slice(0, 10)}.webp`;
  await writeFile(path.join(directory, file), output);
  manifest.push({ id: original.id, file, width: 435, height: 214, bytes: output.length, sha256, source: original.file });
  originalBytes += input.length;
  webpBytes += output.length;
}
await writeFile(path.join(directory, 'index.webp.json'), `${JSON.stringify(manifest, null, 2)}\n`);
const generated = '// Generated by scripts/optimize-adult-artwork.mjs; keep content hashes in filenames.\n'
  + `export const QUESTION_OCEAN_FILES = ${JSON.stringify(manifest.map(item => item.file), null, 2)} as const;\n`;
await writeFile(path.join(root, 'src/products/adult/components/question-ocean-files.ts'), generated);
console.log(JSON.stringify({ count: manifest.length, originalBytes, webpBytes, savedPercent: Math.round((1 - webpBytes / originalBytes) * 100) }, null, 2));

const titleInput = await readFile(path.join(root, 'public/images/integrity-home-title-smile.png'));
const titleOutput = await sharp(titleInput).resize({ width: 880, withoutEnlargement: true }).webp({ quality: 90, effort: 5 }).toBuffer();
const titleMetadata = await sharp(titleOutput).metadata();
const titleHash = createHash('sha256').update(titleOutput).digest('hex').slice(0, 10);
const titleName = `integrity-home-title-smile-${titleHash}.webp`;
await writeFile(path.join(root, 'public/images', titleName), titleOutput);
const title = { src: `/images/${titleName}`, width: titleMetadata.width, height: titleMetadata.height };
await writeFile(path.join(root, 'src/products/adult/components/adult-home-title.ts'), `// Generated by scripts/optimize-adult-artwork.mjs.\nexport const ADULT_HOME_TITLE = ${JSON.stringify(title, null, 2)} as const;\n`);
console.log(JSON.stringify({ titleOriginalBytes: titleInput.length, titleWebpBytes: titleOutput.length, width: titleMetadata.width, height: titleMetadata.height }, null, 2));
